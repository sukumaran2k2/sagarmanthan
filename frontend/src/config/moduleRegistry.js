export const PUBLIC_UI_TABS = [
  'landing',
  'profile',
  'Ministry Contacts',
  'Helpdesk Support',
];

export const TAB_TO_MODULE = (() => {
  const map = {};
  for (const [code, def] of Object.entries(MODULE_PAGES)) {
    for (const tab of def.tabs || []) {
      map[tab] = code;
    }
  }
  return map;
})();

export const IMPLEMENTED_TABS = new Set([
  ...PUBLIC_UI_TABS,
  ...Object.values(MODULE_PAGES).flatMap((def) => def.uiTabs || []),
]);

export function getModuleCodeForTab(tab) {
  if (!tab) return null;
  return TAB_TO_MODULE[tab] || null;
}

export function hasImplementedUi(tab) {
  return IMPLEMENTED_TABS.has(tab);
}
